#!/usr/bin/env python3
"""Generate cuda_pointpillars_ros/include/params.h from the training config.

params.h is a DECODER for whatever the network emits. Every value in it must
mirror the config the model was trained and exported with -- class order, anchor
geometry, voxel grid, pillar capacity. Hand-maintaining that mirror is how this
project ended up decoding one model's output with another model's parameters and
getting confident nonsense out of it.

So: edit config/model.yaml, run this, never edit params.h.

    python3 tools/gen_params_h.py config/model.yaml \
        -o src/cuda_pointpillars_ros/include/params.h

Verify the generator itself with --check, which regenerates and diffs instead of
writing.
"""
